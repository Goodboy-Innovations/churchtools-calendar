/**
 * HubSpot module: platforms/hubspot + the shared bundle in dist/.
 * Writes module.js and module.css into the module folder (committed, so the module
 * can be used straight from git) and release/churchtools-calendar-hubspot-<version>.zip.
 */

import { writeFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { root, readBundle, writeZip } from '../lib.mjs';

const moduleName = 'churchtools-calendar.module';
const moduleDir = resolve(root, 'platforms/hubspot', moduleName);

/** The version is stamped into module.js / module.css by build(). */
export function setVersion() {}

export function versionedFiles() {
  return [`platforms/hubspot/${moduleName}/module.js`, `platforms/hubspot/${moduleName}/module.css`];
}

export function build(version) {
  const { js, css } = readBundle();
  const banner = `/* ChurchTools Calendar HubSpot module ${version}. Generated by \`npm run build:hubspot\`, do not edit. */\n`;

  writeFileSync(resolve(moduleDir, 'module.js'), banner + js);
  writeFileSync(resolve(moduleDir, 'module.css'), banner + css);

  const files = {};
  for (const file of readdirSync(moduleDir)) {
    files[`${moduleName}/${file}`] = { from: resolve(moduleDir, file) };
  }
  return writeZip(`churchtools-calendar-hubspot-${version}.zip`, files);
}
